function b64Bytes(s) {
  const bin = atob(s.replace(/\s/g, ''));
  const u = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) u[i] = bin.charCodeAt(i);
  return u;
}

/** @returns { x: Float32Array, y: Float32Array, kind: Uint8Array, n: number } 로컬 미터, kind 0=글자 1=글러브 2=커프 3=솔기 */
export function unpackTributeDots() {
  const bytes = b64Bytes(TRIBUTE_XY_B64);
  const xy = new Int16Array(bytes.buffer, bytes.byteOffset, bytes.byteLength / 2);
  const kind = b64Bytes(TRIBUTE_KIND_B64);
  const n = TRIBUTE_DOT_COUNT;
  const x = new Float32Array(n), y = new Float32Array(n);
  for (let i = 0; i < n; i++) {
    x[i] = xy[i * 2] * 0.01;
    y[i] = xy[i * 2 + 1] * 0.01;
  }
  return { x, y, kind, n };
}
