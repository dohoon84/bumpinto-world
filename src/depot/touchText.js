// [depot] 터치(모바일) 안내 문구: PC 키 이름(E·G·Esc·WASD·클릭…) → 탭 / 오른쪽 행동 버튼 이름으로.
//   행동 버튼 라벨은 mobileActs() 가 같은 문구에서 뽑으므로 「…」 안 글자와 버튼 글자가 같다.
const RULES = [
  [/①? ?입구 카트 보관소에서 E 로 카트 잡기/g, (m) => `${m.startsWith('①') ? '① ' : ''}입구 카트 보관소에서 「카트 잡기」 버튼`],
  [/먼저 입구 카트 보관소에서 카트를 잡으세요 \(E\)/g, '먼저 입구 카트 보관소에서 「카트 잡기」 버튼을 눌러 주세요'],
  [/선반 상품을 마우스로 클릭\(가운데 조준 X\)/g, '선반 상품을 화면 가운데 두고 탭'],
  [/W\/S 밀기 · A\/D 방향/g, '조이스틱으로 카트 밀기·돌리기'],
  [/WASD 걷기/g, '조이스틱 걷기'],
  [/드래그 둘러보기/g, '화면 드래그 둘러보기'],
  [/상품 클릭 = 집기/g, '가운데 상품 탭 = 집기'],
  [/카트 속 상품도 클릭해 다시 집기/g, '카트 속 상품도 탭해서 다시 집기'],
  [/클릭\/E 집기/g, '탭 또는 「집기」 버튼'],
  [/클릭 = 가리킨 곳에 놓기/g, '탭한 곳에 놓기'],
  [/ · 우클릭\/Esc 취소/g, ' · 「놓기 취소」 버튼'],
  [/ · \(선택\) 휠·Q\/E 돌리기 · R 눕히기 · Tab 아래 받침대 · 방향키 1 cm/g, ' · 「돌리기」 버튼'],
  [/ · G 카트 놓기/g, ' · 「카트 놓기」 버튼'],
  [/Esc 취소/g, '「계산 취소」 버튼'],
  [/E 범카드로 결제/g, '「범카드 결제」 버튼'],
  [/클릭 = /g, '탭 = '],
  [/클릭해서/g, '탭해서'],
  [/클릭/g, '탭'],
  [/카트 옆에서 E 로 다시 잡기/g, '카트 옆에서 「카트 잡기」 버튼으로 다시 잡기'],
  [/· E 로 나가기/g, '· 「출구로 나가기」 버튼'],
  [/E 로 /g, '버튼으로 '],
  // 맨 앞·중간의 "E 무엇" → 「무엇」 버튼
  [/(^|· |에서 )E ([^·(\n—]+?)(?=\s*(?:·|\(|\n|—|$))/g, '$1「$2」 버튼'],
  [/\(E\)/g, '(버튼)'],
  [/옆에서 E(?=\s|$)/g, '옆에서 「카트 잡기」 버튼'],
];
export function touchText(s) {
  if (!s) return s;
  let t = s;
  for (const [re, to] of RULES) t = t.replace(re, to);
  return t;
}
